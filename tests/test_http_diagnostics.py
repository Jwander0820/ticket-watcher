@pytest.mark.parametrize("proxy", ["", "http://private-user:private-password@warp.internal:40001"])
def test_blocked_response_is_diagnosed_without_retry_or_sensitive_logging(
    tmp_path, monkeypatch, caplog, proxy
):
    requests = []

    def handle(request):
        requests.append(request)
        return httpx.Response(
            403,
            headers={
                "Server": "CloudFront",
                "Content-Type": "text/html; charset=utf-8",
                "X-Cache": "Error from cloudfront",
                "X-Amz-Cf-Id": "AbCdEF0123_-=",
                "X-Amz-Cf-Pop": "TPE54-P1",
                "Retry-After": "120",
                "Set-Cookie": "private-cookie",
                "Location": "https://private-redirect.invalid/?token=private-token",
                "Authorization": "Bearer private-token",
            },
            text="<html>Request blocked. Generated by cloudfront. private-body</html>",
        )

    # Exercise production client construction and mounts, but all I/O is mocked.
    real_client = httpx.AsyncClient
    monkeypatch.setattr(
        "ticket_watcher.service.httpx.AsyncClient",
        lambda **kwargs: real_client(transport=httpx.MockTransport(handle), **kwargs),
    )
    monkeypatch.setattr(
        "ticket_watcher.service.httpx.AsyncHTTPTransport",
        lambda **kwargs: httpx.MockTransport(handle),
    )
    config = Config(
        database_path=tmp_path / "state.db",
        targets=(Target("test", "test", "https://ticketplus.com.tw/activity/e000000001"),),
        ticketplus_proxy=proxy,
        system_alerts=False,
    )

    async def scenario():
        async with Watcher(config, clock=Clock()) as watcher:
            result = await watcher.check("test", immediate=True)
            assert result.execution_status == "FAILED"
            assert result.data["error"]["code"] == "BLOCKED"
            diagnostic = result.data["error"]["http_diagnostic"]
            assert diagnostic["status"] == 403
            assert diagnostic["endpoint"] == "getS3"
            assert diagnostic["static_resource"] == "event"
            assert diagnostic["request_number"] == 1
            assert diagnostic["route"] == ("configured_proxy" if proxy else "direct")
            assert diagnostic["user_agent"] == f"TicketWatcher/{__version__}"
            assert diagnostic["server"] == "cloudfront"
            assert diagnostic["content_type"] == "text/html"
            assert diagnostic["x_cache"] == "Error from cloudfront"
            assert diagnostic["response_ids"] == {
                "x-amz-cf-id": "AbCdEF0123_-=",
                "x-amz-cf-pop": "TPE54-P1",
            }
            assert diagnostic["retry_after_seconds"] == 120
            assert diagnostic["body_read"] == "complete"
            assert set(diagnostic["body_signals"]) == {"cloudfront", "request_blocked"}
            assert watcher.store.platform()["paused_reason"] == "BLOCKED"
            entry = watcher.query_log.recent()["entries"][0]
            assert entry["http_diagnostic"] == diagnostic
            assert entry["requests"] == 1
            assert "source_http_diagnostic" in caplog.text
            captured = json.dumps(result.to_dict()) + watcher.query_log.current.read_text()
            assert "private-" not in captured + caplog.text
            assert "warp.internal" not in captured + caplog.text
            # A long Retry-After must not turn BLOCKED into an automatic retry.
            deferred = await watcher.check("test", immediate=True)
            assert deferred.data["reason"] == "PLATFORM_PAUSED"
            assert len(requests) == 1
            assert requests[0].headers["user-agent"] == f"TicketWatcher/{__version__}"

    asyncio.run(scenario())


def test_blocked_single_inventory_request_reports_its_size_and_keeps_all_areas(tmp_path):
    clock = Clock()
    event_hash = public_id("e000000001")
    session_hash = public_id("s000000001")
    url = f"https://ticketplus.com.tw/order/{event_hash}/{session_hash}"
    target = Target("test", "test", url)
    config = Config(database_path=tmp_path / "state.db", targets=(target,), request_gap=(0, 0))
    requests = []

    def handle(request):
        requests.append(request)
        return httpx.Response(403, json={"message": "private-body"})

    async def scenario():
        async with httpx.AsyncClient(transport=httpx.MockTransport(handle)) as client:
            async with Watcher(config, client=client, clock=clock) as watcher:
                watcher.store.cache_metadata(
                    "e000000001",
                    {
                        "title": "test",
                        "sessions": [{"sessionId": "s000000001", "ticketArea": True}],
                    },
                    clock() + 3600,
                )
                watcher.store.cache_metadata(
                    f"area/{event_hash}",
                    {
                        "ticketAreas": [
                            {"ticketAreaId": f"a{i:09d}", "sessionId": "s000000001"}
                            for i in range(132)
                        ],
                    },
                    clock() + 3600,
                )
                result = await watcher.check("test", immediate=True)
                diagnostic = result.data["error"]["http_diagnostic"]
                assert diagnostic["endpoint"] == "get"
                assert diagnostic["requested_ids"] == {"ticketAreaId": 132}
                assert diagnostic["request_number"] == result.data["request_count"] == 1
                assert diagnostic["body_signals"] == []  # Do not invent a block reason.
                sent_ids = [
                    ident
                    for request in requests
                    for ident in request.url.params["ticketAreaId"].split(",")
                ]
                assert len(sent_ids) == len(set(sent_ids)) == 132
                assert len(requests) == 1
                assert watcher.store.platform()["paused_reason"] == "BLOCKED"
                assert not watcher.config.targets[0].item_ids

    asyncio.run(scenario())


@pytest.mark.parametrize("status", [401, 403])
@pytest.mark.parametrize("failure", ["oversized", "compressed", "timeout", "network", "encoding"])
def test_diagnostic_read_failure_preserves_blocked_and_closes_response(
    harness, monkeypatch, status, failure
):
    h, watcher = harness, harness["watcher"]
    monkeypatch.setattr("ticket_watcher.http_diagnostics.BLOCKED_BODY_TIMEOUT", 0.01)
    watcher.transport.config = replace(h["config"], timeout=0.1)
    stream = Chunks(
        {
            "oversized": [b"x" * 20_000, b"never read"],
            "compressed": [gzip.compress(b"x" * 1_000_000), b"never read"],
            "timeout": [b"partial"],
            "network": [b"partial"],
            "encoding": [b"unsupported"],
        }[failure],
        stall=failure == "timeout",
    )

    class BrokenStream(Chunks):
        async def __aiter__(self):
            raise httpx.ReadError("private-network-error")
            yield b""  # pragma: no cover

    if failure == "network":
        stream = BrokenStream([])
    response = httpx.Response(
        status,
        stream=stream,
        headers={
            "Content-Encoding": {"compressed": "gzip", "encoding": "br"}.get(failure, "identity"),
            "CF-Ray": "9acb0123456789ab-TPE",
            "CF-Mitigated": "challenge",
        },
    )
    h["responses"].append(response)
    from ticket_watcher.platforms.ticketplus import TicketPlusAdapter

    watcher.adapter = TicketPlusAdapter(watcher.transport)

    async def scenario():
        result = await asyncio.wait_for(watcher.check("test", immediate=True), 1)
        assert result.data["error"]["code"] == "BLOCKED"
        diagnostic = result.data["error"]["http_diagnostic"]
        assert diagnostic["status"] == status
        assert diagnostic["cf_mitigated"] == "challenge"
        assert diagnostic["body_read"] == {
            "timeout": "timeout",
            "network": "network_error",
        }.get(failure, "unavailable_or_too_large")
        assert watcher.store.platform()["paused_reason"] == "BLOCKED"
        assert len(h["requests"]) == 1
        assert stream.closed and stream.reads <= 1
        assert "private-" not in json.dumps(result.to_dict())

    asyncio.run(scenario())


