@pytest.mark.parametrize("interrupt", ["request_timeout", "cancel"])
def test_interrupted_diagnostic_keeps_known_rejection(harness, monkeypatch, caplog, interrupt):
    from ticket_watcher.platforms.ticketplus import TicketPlusAdapter

    watcher = harness["watcher"]
    watcher.adapter = TicketPlusAdapter(watcher.transport)
    watcher.transport.config = replace(harness["config"], timeout=0.03)
    monkeypatch.setattr("ticket_watcher.http_diagnostics.BLOCKED_BODY_TIMEOUT", 1)
    started = asyncio.Event()

    class SlowBody(Chunks):
        async def __aiter__(self):
            started.set()
            await asyncio.Event().wait()
            yield b""  # pragma: no cover

    stream = SlowBody([])
    harness["responses"].append(httpx.Response(403, stream=stream))

    async def scenario():
        task = asyncio.create_task(watcher.check("test", immediate=True))
        await asyncio.wait_for(started.wait(), 1)
        if interrupt == "cancel":
            task.cancel()
            with pytest.raises(asyncio.CancelledError):
                await task
            assert '"body_read":"cancelled"' in caplog.text
        else:
            result = await asyncio.wait_for(task, 1)
            assert result.data["error"]["code"] == "BLOCKED"
            assert result.data["error"]["http_diagnostic"]["body_read"] == "timeout"
        assert stream.closed
        assert watcher.store.platform()["paused_reason"] == "BLOCKED"
        assert len(harness["requests"]) == 1

    asyncio.run(scenario())


@pytest.mark.parametrize(
    "body,signals",
    [
        (
            "<html>cf-chl-widget challenge-platform captcha private-value</html>",
            {"cloudflare_challenge", "captcha"},
        ),
        (
            "<Error><Code>AccessDenied</Code><Message>private-value</Message></Error>",
            {"access_denied"},
        ),
        ('{"message":"private-value"}', set()),
    ],
)
def test_body_reports_only_recognized_signals(harness, body, signals):
    from ticket_watcher.platforms.ticketplus import TicketPlusAdapter

    watcher = harness["watcher"]
    watcher.adapter = TicketPlusAdapter(watcher.transport)
    harness["responses"].append(httpx.Response(403, text=body))
    result = asyncio.run(watcher.check("test", immediate=True))
    diagnostic = result.data["error"]["http_diagnostic"]
    assert set(diagnostic["body_signals"]) == signals
    assert "private-value" not in watcher.query_log.current.read_text()
